package brew.tools

import brew.lab.LabCards
import brew.remote.BrewCatalog
import brew.remote.BrewSections
import brew.remote.BrewTheme

/**
 * Writes the iOS app's copy of the catalog — drinks, prices, categories, toppings, section heights, the palette, the Lab cards — from the
 * Kotlin sources the documents are made from, so the two apps can't drift apart: change a price in BrewCatalog.kt, run `go run ./cmd/demo
 * render` in backend/, and iOS charges the same price the document shows. GeneratedFilesTest fails while the committed file is out of date.
 */
object SwiftCatalog {
    fun render(): String = buildString {
        append(HEADER)
        appendLine("enum Catalog {")
        appendLine("    static let drinks: [Drink] = [")
        BrewCatalog.DRINKS.forEach { d ->
            appendLine("        Drink(")
            appendLine("            id: ${q(d.id)},")
            appendLine("            name: ${q(d.name)},")
            appendLine("            priceCents: ${cents(d.price)},")
            appendLine("            emoji: ${q(d.emoji)},")
            appendLine("            tile: ${hex(d.tile)},")
            appendLine("            category: ${q(d.category)},")
            appendLine("            hasOptions: ${d.hasOptions},")
            appendLine("            detailsHeight: ${BrewSections.detailsHeight(d.id)}")
            appendLine("        ),")
        }
        appendLine("    ]")
        appendLine("    static let categories: [(key: String, label: String)] = [")
        BrewCatalog.CATEGORIES.forEach { appendLine("        (${q(it.key)}, ${q(it.label)}),") }
        appendLine("    ]")
        appendLine("    /// Bit k of the product page's \"toppings\" mask is toppings[k].")
        appendLine("    static let toppings: [(name: String, cents: Int)] = [")
        BrewCatalog.TOPPINGS.forEach { appendLine("        (${q(it.name)}, ${cents(it.price)}),") }
        appendLine("    ]")
        appendLine("    static let largeCents = ${BrewCatalog.LARGE_CENTS}")
        appendLine("}")
        appendLine()
        appendLine("/// Section heights in points — the numbers the documents are laid out for (dp).")
        appendLine("enum Heights {")
        appendLine("    static let hero: CGFloat = ${BrewSections.HERO_H}")
        appendLine("    static let categories: CGFloat = ${BrewSections.CATEGORIES_H}")
        appendLine("    static let favorites: CGFloat = ${BrewSections.FAVORITES_H}")
        appendLine("    static let forYou: CGFloat = ${BrewSections.FOR_YOU_H}")
        appendLine("    static let promo: CGFloat = ${BrewSections.PROMO_H}")
        appendLine("    /// One product row; the Menu and Favorites lists stack them.")
        appendLine("    static let row: CGFloat = ${BrewSections.ROW_H}")
        appendLine("}")
        appendLine()
        appendLine("/// The palette the documents use, as ARGB.")
        appendLine("enum Palette {")
        listOf(
                "tan" to BrewTheme.TAN,
                "tanDark" to BrewTheme.TAN_DARK,
                "tanSoft" to BrewTheme.TAN_SOFT,
                "ink" to BrewTheme.INK,
                "muted" to BrewTheme.MUTED,
                "green" to BrewTheme.GREEN,
                "red" to BrewTheme.RED,
                "butter" to BrewTheme.BUTTER,
            )
            .forEach { (name, argb) -> appendLine("    static let $name: UInt32 = ${hex(argb)}") }
        appendLine("}")
        appendLine()
        appendLine("/// The Lab's shader cards, in order (their documents are bundled as lab_i-<n>.rc).")
        appendLine("enum LabCards {")
        appendLine("    static let all: [(title: String, height: CGFloat)] = [")
        LabCards.all.forEach { appendLine("        (${q(it.title)}, ${it.heightDp}),") }
        appendLine("    ]")
        appendLine("}")
    }

    private val HEADER =
        """
        // GENERATED by go run ./cmd/demo render from shared/src/main/kotlin/brew
        // (BrewCatalog, BrewSections, BrewTheme, LabCards).
        // Do not edit: change the Kotlin and run the script again.

        import CoreGraphics

        struct Drink: Identifiable, Sendable {
            let id: String
            let name: String
            let priceCents: Int
            let emoji: String
            let tile: UInt32
            let category: String
            /// Sugar / size / ice / toppings on its page (cakes and beans have none).
            let hasOptions: Bool
            /// The height its product page document is laid out for, in points (dp).
            let detailsHeight: CGFloat
        }

        """
            .trimIndent() + "\n\n"

    private fun q(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

    private fun hex(argb: Int) = "0x%08X".format(argb)

    private fun cents(p: Float) = kotlin.math.round(p * 100f).toInt()
}
